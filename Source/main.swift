    let restored = try! JSONDecoder().decode(Clip.self, from: JSONEncoder().encode(clip))
    precondition(restored.category == .work)
    let recopy = try! JSONDecoder().decode(Clip.self, from: legacy)
    precondition(recopy.preservingCategory(from: restored).category == .work)
    clip.categoryOverride = nil
    precondition(clip.category == .personal)
    print("PASS: local classification, ambiguous text, legacy history, saved overrides, recopy preservation, automatic reset")
}

