    @objc func openHistory() {
        target = NSWorkspace.shared.frontmostApplication
        showPicker()
    }
    func showPicker() {
        capture()
        search.stringValue = ""
        categoryFilter.selectedSegment = 0
        refresh()
        panel.center()
        NSApp.activate(ignoringOtherApps: true)
        panel.makeKeyAndOrderFront(nil)
        panel.makeFirstResponder(search)
    }
    func refresh() {
        let selectedID = filtered.indices.contains(table.selectedRow) ? filtered[table.selectedRow].id : nil
        let query = search.stringValue
        let index = categoryFilter.selectedSegment - 1
        let category = ClipCategory.allCases.indices.contains(index) ? ClipCategory.allCases[index] : nil
        filtered = clips.filter {
            (category == nil || $0.category == category) &&
            (query.isEmpty || $0.title.localizedCaseInsensitiveContains(query) || $0.kind.localizedCaseInsensitiveContains(query) || $0.category.rawValue.localizedCaseInsensitiveContains(query))
        }
        table.reloadData()
        if !filtered.isEmpty {
            let row = filtered.firstIndex { $0.id == selectedID } ?? 0
            table.selectRowIndexes(IndexSet(integer: row), byExtendingSelection: false)
        }
        updateCategoryEditor()
        footer.stringValue = filtered.isEmpty ? "No hay elementos en este filtro. Prueba Todos o cambia la búsqueda." : "↑↓ elegir   ·   Enter pegar   ·   Esc cerrar   ·   \(filtered.count) elementos"
    }
    @objc func filterChanged() { refresh() }
    func tableViewSelectionDidChange(_ notification: Notification) { updateCategoryEditor() }
    func updateCategoryEditor() {
        guard filtered.indices.contains(table.selectedRow) else { categoryEditor.isEnabled = false; return }
        categoryEditor.isEnabled = true
        let clip = filtered[table.selectedRow]
        categoryEditor.item(at: 0)?.title = "Automática · \(TextClassifier.classify(clip.kind == "Texto" ? clip.title : "").rawValue)"
        if let value = clip.categoryOverride, let index = ClipCategory.allCases.firstIndex(where: { $0.rawValue == value }) {
            categoryEditor.selectItem(at: index + 1)
        } else { categoryEditor.selectItem(at: 0) }
    }
    @objc func categoryChanged() {
        guard filtered.indices.contains(table.selectedRow), let index = clips.firstIndex(where: { $0.id == filtered[table.selectedRow].id }) else { return }
        let choice = categoryEditor.indexOfSelectedItem - 1
        clips[index].categoryOverride = ClipCategory.allCases.indices.contains(choice) ? ClipCategory.allCases[choice].rawValue : nil
        save()
        refresh()
    }
