struct Clip: Codable {
    var id: String
    var date: Date
    var title: String
    var kind: String
    var items: [[String: Data]]
    var categoryOverride: String?
    var category: ClipCategory {
        if let value = categoryOverride, let category = ClipCategory(rawValue: value) { return category }
        return kind == "Texto" ? TextClassifier.classify(title) : .other
    }
    func preservingCategory(from previous: Clip?) -> Clip {
        var result = self
        result.categoryOverride = previous?.categoryOverride
        return result
    }
    var size: Int { items.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } } }
}

enum ClipCategory: String, CaseIterable {
    case personal = "Datos personales"
    case work = "Trabajo"
    case other = "Otros"
}

enum TextClassifier {
    // Conservative local hints, not identity validation or semantic AI.
    static let personal = try! NSRegularExpression(pattern: #"(?i)\b(?:\d{8}[- ]?[a-z]|[xyz]\d{7}[- ]?[a-z])\b|\b(?:dni|nie|pasaporte|domicilio|direccion postal|fecha de nacimiento|numero de telefono|telefono personal)\s*[:=]|\b(?:calle|avenida|avda\.?|paseo|plaza|c/)[ \t]+[^\n,]{2,60},?\s+\d{1,5}\b"#)
    static let work = try! NSRegularExpression(pattern: #"(?i)\b(?:trabajo|laboral|cliente|clientes|factura|facturas|presupuesto|reunion|reuniones|proyecto|proyectos|entregable|deadline|sprint|ticket|tickets|pull request|deploy|meeting|invoice|airtable|jira|slack)\b"#)
    static func classify(_ text: String) -> ClipCategory {
        let normalized = text.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: Locale(identifier: "es"))
        let range = NSRange(normalized.startIndex..., in: normalized)
        // Personal data takes precedence when a work message includes an identifier/address.
        if personal.firstMatch(in: normalized, range: range) != nil { return .personal }
        if work.firstMatch(in: normalized, range: range) != nil { return .work }
        return .other
    }
}

enum ClipCodec {
    static let limit = 12 * 1024 * 1024
    static func capture(_ board: NSPasteboard) -> Clip? {
        let blocked = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        let source = board.pasteboardItems ?? []
        guard !source.contains(where: { item in item.types.contains { type in blocked.contains(type.rawValue) } }) else { return nil }
        var size = 0
        var items: [[String: Data]] = []
        for item in source {
            var values: [String: Data] = [:]
            for type in item.types {
                // Preserve portable representations, never application-private promises.
                guard type.rawValue.hasPrefix("public.") || ["com.adobe.pdf", "NeXT TIFF v4.0 pasteboard type"].contains(type.rawValue) else { continue }
                if let data = item.data(forType: type) {
                    size += data.count
                    guard size <= limit else { return nil }
                    values[type.rawValue] = data
                }
            }
            if !values.isEmpty { items.append(values) }
        }
        guard !items.isEmpty else { return nil }
        var digest = SHA256()
        for item in items {
            digest.update(data: Data([0]))
            for key in item.keys.sorted() {
                digest.update(data: Data(key.utf8)); digest.update(data: Data([0]))
                digest.update(data: item[key]!)
            }
        }
        let files = source.compactMap { $0.string(forType: .fileURL) }.compactMap(URL.init(string:))
        let text = board.string(forType: .string)
        let image = source.contains { $0.types.contains(.png) || $0.types.contains(.tiff) }
        let kind = !files.isEmpty ? "Archivo" : image ? "Imagen" : text != nil ? "Texto" : "Contenido"
        let title = !files.isEmpty ? files.map(\.lastPathComponent).joined(separator: ", ") : text ?? (image ? "Imagen copiada" : "Contenido copiado")
        return Clip(id: digest.finalize().map { String(format: "%02x", $0) }.joined(), date: Date(), title: String(title.prefix(20000)), kind: kind, items: items)
    }
    static func restore(_ clip: Clip, to board: NSPasteboard) -> Bool {
        let items = clip.items.map { values -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in values { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return item
        }
        board.clearContents()
        return board.writeObjects(items)
    }
}

