    func setupHotKey() {
        if hotKeyHandler == nil {
            var eventType = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            hotKeyStatus = InstallEventHandler(GetApplicationEventTarget(), { _, event, context in
                guard let event, let context else { return OSStatus(eventNotHandledErr) }
                var identifier = EventHotKeyID()
                let result = GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil, MemoryLayout<EventHotKeyID>.size, nil, &identifier)
                guard result == noErr, identifier.signature == 0x50525441, identifier.id == 1 else { return OSStatus(eventNotHandledErr) }
                let app = Unmanaged<App>.fromOpaque(context).takeUnretainedValue()
                guard !app.paused, !app.pasting, !app.panel.isVisible else { return noErr }
                app.openHistory()
                return noErr
            }, 1, &eventType, Unmanaged.passUnretained(self).toOpaque(), &hotKeyHandler)
            guard hotKeyStatus == noErr else { updateMenu(); writeStatus(); return }
        }
        guard hotKey == nil, !paused else { return }
        hotKeyStatus = RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(cmdKey | optionKey), EventHotKeyID(signature: 0x50525441, id: 1), GetApplicationEventTarget(), 0, &hotKey)
        updateMenu()
        writeStatus()
    }

    func writeStatus() {
        let status: [String: Any] = ["pid": ProcessInfo.processInfo.processIdentifier, "shortcutRegistered": hotKey != nil, "shortcutError": hotKeyStatus, "accessibility": AXIsProcessTrusted(), "paused": paused]
        if let data = try? JSONSerialization.data(withJSONObject: status, options: .sortedKeys) {
            try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try? data.write(to: directory.appendingPathComponent("status.json"), options: .atomic)
        }
    }

    func capture() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard !paused, let captured = ClipCodec.capture(board) else { return }
        let clip = captured.preservingCategory(from: clips.first { $0.id == captured.id })
        clips.removeAll { $0.id == clip.id }
        clips.insert(clip, at: 0)
        while clips.count > 100 || clips.reduce(0, { $0 + $1.size }) > 32 * 1024 * 1024 { clips.removeLast() }
        save()
        if panel.isVisible { refresh() }
    }

    func save() {
        let snapshot = clips
        let directory = self.directory, url = historyURL
        diskQueue.async {
            do {
                try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
                let data = try JSONEncoder().encode(snapshot)
                try data.write(to: url, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            } catch {
                DispatchQueue.main.async { self.footer.stringValue = "No se pudo guardar el historial en disco." }
            }
        }
    }

